CREATE TABLE IF NOT EXISTS users (
    id            INT UNSIGNED NOT NULL AUTO_INCREMENT,
    username      VARCHAR(50)  NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_users_username (username),
    UNIQUE KEY uq_users_email (email)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS joueurs (
    id     INT UNSIGNED      NOT NULL,
    nom    VARCHAR(150)      NOT NULL,
    poste  VARCHAR(20)       NULL,
    taille SMALLINT UNSIGNED NULL,
    equipe VARCHAR(100)      NULL,
    PRIMARY KEY (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS cartes_utilisateur (
    id        BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id   INT UNSIGNED    NOT NULL,
    joueur_id INT UNSIGNED    NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_cartes_user   FOREIGN KEY (user_id)   REFERENCES users (id)   ON DELETE CASCADE,
    CONSTRAINT fk_cartes_joueur FOREIGN KEY (joueur_id) REFERENCES joueurs (id) ON DELETE CASCADE
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

